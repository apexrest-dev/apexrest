async function formPreview(t: import('node:test').TestContext, schema: string) {
  const { app, assets } = await workspace(t, {
    'pages/p00005-person.apx': FORM_PAGE,
    '.apex-local/02-people.sql': schema,
  });
  const server = new PreviewServer({ sourceDir: app, assetsDir: assets, database: ':memory:' });
  const renderer = server.renderer;
  const submit = (request: string, items: Record<string, string>) => {
    const session: Session = { id: '1', user: 'SCOTT', items: { ...items }, pagination: {} };
    const ctx = renderer.prepareSubmit(session, '5', request);
    assert.equal(renderer.processForm(ctx, 'person', undefined), true);
    return session.items;
  };
  const fetch = (id: string) => {
    const session: Session = { id: '1', user: 'SCOTT', items: { P5_ID: id }, pagination: {} };
    const ctx = renderer.prepareSubmit(session, '5', '');
    renderer.initializeForm(ctx, 'person');
    return session.items;
  };
  return { server, renderer, submit, fetch };
}

test('form DML stores date items canonically and fetch formats them with the mask', async (t) => {
  const { server, submit, fetch } = await formPreview(
    t,
    `create table people (id number generated always as identity primary key, name varchar2(50), born date);
insert into people (name, born) values ('Seeded', to_date('2018-03-01', 'YYYY-MM-DD'));`,
  );
  const created = submit('CREATE', { P5_ID: '', P5_NAME: 'Ada', P5_BORN: '10-JAN-2020' });
  assert.equal(created.P5_ID, '2');
  assert.deepEqual(
    server.db.query('select id, born from people order by id').rows.map((row) => row.BORN),
    ['2018-03-01 00:00:00', '2020-01-10 00:00:00'],
  );
  submit('SAVE', { P5_ID: '2', P5_NAME: 'Ada', P5_BORN: '11-FEB-2021' });
  assert.equal(server.db.scalar('select born from people where id = 2'), '2021-02-11 00:00:00');
  assert.equal(fetch('2').P5_BORN, '11-FEB-2021');
  assert.equal(fetch('1').P5_BORN, '01-MAR-2018');
  // identity keys are generated without a diagnostic
  assert.equal(
    server.renderer.diagnostics.some((entry) => /max \+ 1/u.test(entry.message)),
    false,
  );
  assert.equal(canonicalDate('2020-01-10'), '2020-01-10 00:00:00');
  assert.equal(canonicalDate('not a date', 'DD-MON-YYYY'), 'not a date');
});

test('form insert reports a locally generated key when Oracle has no key source', async (t) => {
  const { server, submit } = await formPreview(
    t,
    `create table people (id number primary key, name varchar2(50), born date);
insert into people values (7, 'Seeded', null);`,
  );
  const created = submit('CREATE', { P5_ID: '', P5_NAME: 'Bob', P5_BORN: '' });
  assert.equal(created.P5_ID, '8');
  const warning = server.renderer.diagnostics.find((entry) => /max \+ 1/u.test(entry.message));
  assert.equal(warning?.level, 'warning');
  assert.match(warning!.message, /PEOPLE\.ID has no identity, default or insert trigger/u);
  assert.equal(server.db.scalar('select born from people where id = 8'), null);
});

test('form insert uses a column default or seed trigger for the key', async (t) => {
  const { server, submit } = await formPreview(
    t,
    `create sequence people_seq start with 100;
create table people (id number default people_seq.nextval primary key, name varchar2(50), born date);
create table audit_rows (id number primary key, note varchar2(50));
create or replace trigger audit_rows_bi before insert on audit_rows for each row
begin
  :new.id := 1;
end;
/
`,
  );
  const created = submit('CREATE', { P5_ID: '', P5_NAME: 'Cy', P5_BORN: '' });
  assert.equal(created.P5_ID, '100');
  assert.equal(server.db.scalar('select name from people where id = 100'), 'Cy');
  assert.equal(server.db.keySource('audit_rows', 'ID'), 'trigger');
  assert.equal(
    server.renderer.diagnostics.some((entry) => /max \+ 1/u.test(entry.message)),
    false,
  );
});

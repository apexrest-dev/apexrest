test('json_value, json_query and json_exists follow Oracle paths', (t) => {
  const db = database(t);
  const doc = JSON.stringify({
    order: {
      id: 7,
      lines: [
        { sku: 'A-1', qty: 2.5 },
        { sku: 'B-2', qty: 1 },
      ],
    },
    ok: true,
  });
  const row = one(
    db,
    `select json_value(:doc, '$.order.lines[0].sku') sku,
            json_value(:doc, '$.order.lines[last].sku') last_sku,
            json_value(:doc, '$.order.lines[0].qty' returning number) qty,
            json_value(:doc, '$.order.id') id_text,
            json_value(:doc, '$.ok') ok,
            json_value(:doc, '$.order' null on error) obj,
            json_value(:doc, '$.missing') missing,
            json_query(:doc, '$.order.lines[1]') line,
            json_query(:doc, '$.order.lines[*].sku' with wrapper) skus,
            json_exists(:doc, '$.order.lines[1].sku') has_sku,
            json_exists(:doc, '$.order.nothing') has_nothing
       from dual`,
    { DOC: doc },
  );
  assert.deepEqual(
    { ...row },
    {
      SKU: 'A-1',
      LAST_SKU: 'B-2',
      QTY: 2.5,
      ID_TEXT: '7',
      OK: 'true',
      OBJ: null,
      MISSING: null,
      LINE: '{"sku":"B-2","qty":1}',
      SKUS: '["A-1","B-2"]',
      HAS_SKU: 1,
      HAS_NOTHING: 0,
    },
  );
  assert.equal(db.scalar(`select count(*) from dual where json_exists(:doc, '$.ok')`, { DOC: doc }), 1);
});

test('LISTAGG measures may nest parentheses at any depth', (t) => {
  const db = database(t);
  const today = new Date();
  const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  const expected = [0, 1, 2]
    .map((offset) => {
      const date = new Date(today.getFullYear(), today.getMonth(), today.getDate() + offset);
      return `${days[date.getDay()]} ${String(date.getDate()).padStart(2, '0')}`;
    })
    .join(' · ');
  assert.equal(
    db.scalar(
      "select listagg(to_char(trunc(sysdate) + level - 1, 'Dy DD'), ' · ') within group (order by level) from dual connect by level <= 3",
    ),
    expected,
  );
  db.runScript('create table v (n number);\ninsert into v values (1.5);\ninsert into v values (2);', 'seed');
  assert.equal(db.scalar("select listagg(n * 2, ',') within group (order by n) from v"), '3,4');
  assert.equal(
    db.scalar('select listagg(distinct upper(substr(to_char(n), 1, 1))) within group (order by 1) from v'),
    '1,2',
  );
  assert.match(
    translateOracleSql("select listagg(a, ', ' on overflow truncate) within group (order by a) from t"),
    /group_concat\(apex_local_text\(a\), ', ' order by a\)/u,
  );
});

test('regular expressions translate POSIX classes and match parameters', (t) => {
  const db = database(t);
  const row = one(
    db,
    `select regexp_like('Jane Doe', '^[[:upper:]][[:lower:]]+[[:space:]][[:alpha:]]+$') name_ok,
            regexp_like('abc', '^ABC$', 'i') ci, regexp_like('abc', '^ABC$', 'ic') cs,
            regexp_replace('a1b22c', '[[:digit:]]+', '#') digits,
            regexp_count('a.b,c!', '[[:punct:]]') punct,
            regexp_substr('x-42-y', '[[:alnum:]]+', 1, 2) second,
            regexp_like('a' || chr(10) || 'b', 'a.b', 'n') dotall,
            regexp_like('a' || chr(10) || 'b', '^b$', 'm') multiline,
            regexp_like('abc', 'a b c', 'x') extended,
            regexp_instr('hello world', 'o', 1, 2) second_o
       from dual`,
  );
  assert.deepEqual(
    { ...row },
    {
      NAME_OK: 1,
      CI: 1,
      CS: 0,
      DIGITS: 'a#b#c',
      PUNCT: 3,
      SECOND: '42',
      DOTALL: 1,
      MULTILINE: 1,
      EXTENDED: 1,
      SECOND_O: 8,
    },
  );
  assert.ok(oracleRegExp('^[^[:space:]]+@[^[:space:]]+$').test('a@b.c'));
  assert.ok(!oracleRegExp('^[^[:space:]]+@[^[:space:]]+$').test('a b@c'));
  assert.ok(oracleRegExp('^[]a]+$').test(']a'));
  // identity escapes JavaScript's Unicode mode rejects still compile
  assert.ok(oracleRegExp('^\\#\\d+$').test('#12'));
});


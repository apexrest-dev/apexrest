function database(t: import('node:test').TestContext): LocalDatabase {
  const db = new LocalDatabase(':memory:');
  t.after(() => db.close());
  return db;
}

const one = (db: LocalDatabase, sql: string, binds = {}) => db.query(sql, binds).rows[0]!;

test('seed scripts accept ANSI datetime literals, DDL defaults, identities and comments', (t) => {
  const db = database(t);
  const problems = db.runScript(
    `-- Seed data; the first line is a comment ending with a semicolon;
create table events (
  id number generated by default on null as identity primary key,
  title varchar2(100) default on null 'Untitled',
  created_on date default sysdate not null,
  stamped timestamp default systimestamp,
  starts date default date '2020-01-01',
  code varchar2(32) default sys_guid()
);
-- a comment before a sequence
create sequence event_seq start with 50;
create table tickets (
  ticket_id number default event_seq.nextval primary key,
  title varchar2(100)
);
insert into events (title, starts) values ('Launch', date '2026-03-01');
insert into events (title, starts) values ('Review', timestamp '2026-03-02 14:30:00');
/* block comment */ insert into tickets (title) values ('First');
`,
    'seed.sql',
  );
  assert.deepEqual(problems, []);
  const rows = db.query('select id, title, created_on, starts, code from events order by id').rows;
  assert.deepEqual(
    rows.map((row) => [row.ID, row.TITLE, row.STARTS]),
    [
      [1, 'Launch', '2026-03-01 00:00:00'],
      [2, 'Review', '2026-03-02 14:30:00'],
    ],
  );
  assert.match(String(rows[0]!.CREATED_ON), /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/u);
  assert.match(String(rows[0]!.CODE), /^[0-9A-F]{32}$/u);
  assert.equal(db.scalar('select ticket_id from tickets'), 50);
  assert.equal(db.keySource('events', 'ID'), 'identity');
  assert.equal(db.keySource('tickets', 'TICKET_ID'), 'default');
  // runtime SQL too
  assert.equal(db.scalar("select to_char(date '2026-03-01' + 1, 'YYYY-MM-DD') from dual"), '2026-03-02');
  assert.equal(db.scalar("select count(*) from events where starts >= date '2026-03-02'"), 1);
  assert.deepEqual(splitScript('-- only a comment;\nselect 1 from dual;'), ['select 1 from dual']);
});


test('date arithmetic works on any date expression; date - date is days', (t) => {
  const db = database(t);
  db.runScript(
    `create table shifts (id integer primary key, starts date);
insert into shifts values (1, to_date('2026-01-30 22:00', 'YYYY-MM-DD HH24:MI'));
insert into shifts values (2, to_date('2026-02-28', 'YYYY-MM-DD'));`,
    'seed',
  );
  const today = new Date();
  const tomorrow = new Date(today.getFullYear(), today.getMonth(), today.getDate() + 1);
  const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  assert.equal(
    db.scalar("select to_char(trunc(sysdate) + 1, 'Dy DD') from dual"),
    `${days[tomorrow.getDay()]} ${String(tomorrow.getDate()).padStart(2, '0')}`,
  );
  const rows = db.query(
    `select starts + 1 plus_day, starts - 0.5 minus_half, starts + 1/24 plus_hour,
            to_date('2026-03-01', 'YYYY-MM-DD') - starts gap, trunc(starts) + 2 - 1 chained
       from shifts order by id`,
  ).rows;
  assert.deepEqual(
    rows.map((row) => ({ ...row })),
    [
      {
        PLUS_DAY: '2026-01-31 22:00:00',
        MINUS_HALF: '2026-01-30 10:00:00',
        PLUS_HOUR: '2026-01-30 23:00:00',
        GAP: 29.0833333333333,
        CHAINED: '2026-01-31',
      },
      {
        PLUS_DAY: '2026-03-01 00:00:00',
        MINUS_HALF: '2026-02-27 12:00:00',
        PLUS_HOUR: '2026-02-28 01:00:00',
        GAP: 1,
        CHAINED: '2026-03-01',
      },
    ],
  );
  assert.equal(
    db.scalar("select to_date('2026-03-01', 'YYYY-MM-DD') - to_date('2026-01-01', 'YYYY-MM-DD') from dual"),
    59,
  );
  assert.equal(db.scalar('select :d + 7 from dual', { D: '2026-01-01' }), '2026-01-08');
  // numbers are still numbers
  assert.equal(db.scalar('select 2 + 3 - 1 from dual'), 4);
  assert.equal(db.scalar('select count(*) - 1 from shifts'), 1);
  assert.equal(sqlArithmetic('10-JAN-2020', '+', 1), '2020-01-11');
  assert.equal(sqlArithmetic('5', '-', 2), 3n);
});

test('division is real division and numbers convert to text as Oracle does', (t) => {
  const db = database(t);
  db.runScript(
    'create table sizes (bytes integer, total integer);\ninsert into sizes values (6299, 3);',
    'seed',
  );
  const row = one(
    db,
    `select round(6299 / 1024, 1) kb, round(bytes / 1024, 1) kb2, total / 2 half, 7 / 7 whole,
            0.15 * 100 || '%' pct, 'x' || 2.50 trailing, to_char(0.5) half_text, to_char(-0.25) neg,
            1 + 2 || ' items' sum_text, 'n=' || bytes / 1024 ratio
       from sizes`,
  );
  assert.deepEqual(
    { ...row },
    {
      KB: 6.2,
      KB2: 6.2,
      HALF: 1.5,
      WHOLE: 1,
      PCT: '15%',
      TRAILING: 'x2.5',
      HALF_TEXT: '.5',
      NEG: '-.25',
      SUM_TEXT: '3 items',
      RATIO: 'n=6.1513671875',
    },
  );
  assert.equal(db.scalar('select 0.1 + 0.2 from dual'), 0.3);
  assert.equal(oracleNumberText(15.000000000000002), '15');
  assert.equal(oracleNumberText(0.000001), '.000001');
  assert.equal(oracleNumberText(-1.5), '-1.5');
  assert.equal(oracleNumberText(1e21), '1000000000000000000000');
  assert.equal(db.scalar("select to_char(12.5, 'TM9') from dual"), '12.5');
});


test('seed scripts keep PL/SQL units, drop SQL*Plus commands and Oracle-only statements', () => {
  const units = splitScriptUnits(`set define off
create table t (id number);
show errors
/* a comment before the unit */ create or replace package p is
  procedure x;
end;
/
show errors
comment on table t is 'not local';
begin
  null;
end;
/
`);
  assert.deepEqual(
    units.map((unit) => unit.kind),
    ['sql', 'plsql', 'sql', 'plsql'],
  );
  assert.equal(describeUnit(units[1]!.text).kind, 'package');
  assert.equal(describeUnit(units[1]!.text).name, 'p');
  assert.equal(describeUnit(units[3]!.text).kind, 'block');
  assert.deepEqual(oracleSeedStatements("comment on table t is 'x'"), []);
  assert.deepEqual(oracleSeedStatements('alter trigger t_biu enable'), []);
  assert.deepEqual(
    oracleSeedStatements('alter table t add constraint t_fk foreign key (a) references u (id)'),
    [],
  );
  assert.deepEqual(
    oracleSeedStatements('alter table "T" add constraint "T_PK" primary key ("ID") using index enable'),
    ['create unique index if not exists "T_PK" on "T" ("ID")'],
  );
  assert.deepEqual(oracleSeedStatements('alter table t add (a number, b varchar2(10))'), [
    'alter table "t" add column a number',
    'alter table "t" add column b varchar2(10)',
  ]);
  assert.deepEqual(oracleSeedStatements('drop table x cascade constraints purge'), [
    'drop table if exists "x"',
  ]);
});

test('table DDL loses identity options, time zones, NUMBER(*,0) and physical options', () => {
  const db = new LocalDatabase(':memory:');
  const problems = db.runScript(
    `CREATE TABLE "T" ("ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE,
  "V" NUMBER(*,0), "AT" TIMESTAMP (6) WITH LOCAL TIME ZONE, "D" INTERVAL DAY (2) TO SECOND (6),
  PRIMARY KEY ("ID") USING INDEX ENABLE) SEGMENT CREATION IMMEDIATE ROWDEPENDENCIES TABLESPACE USERS;
insert into t (v) values (1);
insert into t (v) values (2);`,
    'ddl.sql',
  );
  assert.deepEqual(problems, []);
  assert.deepEqual(db.query('select id, v from t order by id').rows, [
    { ID: 1, V: 1 },
    { ID: 2, V: 2 },
  ]);
  assert.doesNotMatch(cleanTableDdl('create table x (a number) tablespace users'), /tablespace/iu);
  // an identity column that is not the primary key is numbered after the insert
  db.runScript(
    'create table u (code varchar2(5) primary key, seq number generated always as identity not null);',
    'u.sql',
  );
  db.execute("insert into u (code) values ('a')");
  db.execute("insert into u (code) values ('b')");
  assert.deepEqual(
    db.query('select code, seq from u order by code').rows.map((row) => ({ ...row })),
    [
      { CODE: 'a', SEQ: 1 },
      { CODE: 'b', SEQ: 2 },
    ],
  );
});

test('supporting-object install scripts run in the order install-scripts.apx declares', async (t) => {
  const root = await mkdtemp(path.join(tmpdir(), 'apexrest-install-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, 'supporting-objects', 'install-scripts'), { recursive: true });
  for (const name of ['a-data.sql', 'b-tables.sql'])
    await writeFile(path.join(root, 'supporting-objects', 'install-scripts', name), '');
  await writeFile(
    path.join(root, 'supporting-objects', 'install-scripts.apx'),
    `installScript "Data" (
    execution {
        sequence: 20
    }
    script {
        contentFile: a-data.sql
    }
)

installScript "Tables" (
    execution {
        sequence: 10
    }
    script {
        contentFile: b-tables.sql
    }
)
`,
  );
  assert.deepEqual(
    installScripts(root).map((file) => path.basename(file)),
    ['b-tables.sql', 'a-data.sql'],
  );
});

test('BEFORE row triggers fill keys and audit columns through SQLite AFTER triggers', () => {
  const db = new LocalDatabase(':memory:');
  const problems = db.runScript(
    `create sequence t_seq;
create table t (id number not null, name varchar2(10) not null, row_version number not null, created date not null, created_by varchar2(255) not null);
create or replace trigger t_biu before insert or update on t for each row
begin
    if :new.id is null then
        select t_seq.nextval into :new.id from dual;
    end if;
    if inserting then
        :new.created := sysdate;
        :new.created_by := nvl(wwv_flow.g_user, user);
        :new.row_version := 1;
    elsif updating then
        :new.row_version := nvl(:old.row_version, 0) + 1;
    end if;
    :new.name := upper(:new.name);
    audit_pkg.log(:new.id);
end;
/
insert into t (name) values ('a');
update t set name = 'b' where id = 1;
`,
    'trigger.sql',
  );
  assert.equal(problems.length, 2, 'the package call is reported once per event');
  assert.match(problems[0]!, /trigger t_biu \(insert\): not run locally: call to audit_pkg\.log/u);
  const row = db.query('select id, name, row_version, created_by from t').rows[0]!;
  assert.deepEqual({ ...row }, { ID: 1, NAME: 'B', ROW_VERSION: 2, CREATED_BY: 'APEX_LOCAL' });
  assert.match(
    relaxNotNull('create table x (a number not null, b number not null)', ['a']),
    /\(a number, b number not null\)/u,
  );
});

test('Oracle (+) outer joins become LEFT JOINs, block by block', () => {
  assert.equal(
    rewriteOuterJoins(
      'select e.ename, d.dname from emp e, dept d where e.deptno = d.deptno (+) and e.sal > 0',
    ),
    'select e.ename, d.dname from emp e left join dept d on e.deptno = d.deptno where e.sal > 0',
  );
  assert.equal(
    rewriteOuterJoins('select * from (select a.x from a, b where a.id = b.id(+) and b.kind(+) = 1) t'),
    'select * from (select a.x from a left join b on a.id = b.id and b.kind = 1) t',
  );
  // a marker on an unqualified column is left alone
  assert.equal(rewriteOuterJoins('select * from a, b where x = y (+)'), 'select * from a, b where x = y (+)');
});

test('SQL shims: #OWNER#, sys-qualified names, SELECT UNIQUE, interval literals and Oracle functions', () => {
  const db = new LocalDatabase(':memory:');
  db.runScript(
    "create table emp (empno number, ename varchar2(10));\ninsert into emp values (1, 'KING');",
    's.sql',
  );
  assert.equal(db.scalar('select count(*) from #OWNER#.emp'), 1);
  assert.equal(db.scalar('select count(*) from sys.dual'), 1);
  assert.equal(db.scalar('select unique ename from emp'), 'KING');
  assert.equal(
    db.scalar("select round((date '2026-01-02' + interval '12' hour) - date '2026-01-02', 2) from dual"),
    0.5,
  );
  assert.equal(db.scalar("select numtodsinterval(6, 'HOUR') from dual"), 0.25);
  assert.equal(typeof db.scalar("select ora_hash('x', 9) from dual"), 'number');
  const value = db.scalar('select dbms_random.value from dual');
  assert.ok(
    typeof value === 'number' && value >= 0 && value < 1,
    'dbms_random.value without parentheses is a call',
  );
  assert.match(
    translateOracleSql('select e.x from t e where e.id = 1 start with p is null connect by prior id = p'),
    /with recursive/iu,
  );
});

test('Oracle data dictionary views describe the local schema and its PL/SQL', () => {
  const db = new LocalDatabase(':memory:');
  db.runScript(
    `create table emp (empno number primary key, ename varchar2(10) not null);
create or replace package p is
  function f return number;
end;
/
`,
    'dict.sql',
  );
  assert.deepEqual(db.query("select table_name from user_tables where table_name = 'EMP'").rows, [
    { TABLE_NAME: 'EMP' },
  ]);
  assert.deepEqual(
    db
      .query("select column_name, nullable from all_tab_columns where table_name = 'EMP' order by column_id")
      .rows.map((row) => ({ ...row })),
    [
      { COLUMN_NAME: 'EMPNO', NULLABLE: 'Y' },
      { COLUMN_NAME: 'ENAME', NULLABLE: 'N' },
    ],
  );
  assert.deepEqual(
    db
      .query("select object_type from user_objects where object_name = 'P'")
      .rows.map((row) => row.OBJECT_TYPE),
    ['PACKAGE'],
  );
  assert.equal(db.scalar("select count(*) from user_source where name = 'P'"), 3);
  assert.equal(db.scalar("select count(*) from session_privs where privilege = 'CREATE JOB'"), 1);
});

test('package library: specs and bodies merge, overloads resolve by arguments', () => {
  const library = buildLibrary([
    {
      kind: 'package',
      name: 'p',
      source:
        'create or replace package p as\n  g_count number := 0;\n  function f(a number) return number;\nend p;',
      script: 's',
    },
    {
      kind: 'package body',
      name: 'p',
      source: `create or replace package body p as
  function f(a number) return number is begin return a; end;
  function f(a varchar2, b varchar2) return varchar2 is begin return a || b; end;
  function g return number is begin return 1; end;
begin
  g_count := 10;
end p;`,
      script: 's',
    },
  ]);
  assert.deepEqual(library.problems, []);
  const pkg = library.packages.get('p')!;
  assert.ok(pkg.init, 'the initialization section is kept');
  assert.equal(pkg.routines.get('f')!.length, 2);
  assert.equal(pickOverload(pkg.routines.get('f')!, 2, [])!.params.length, 2);
  assert.equal(pickOverload(pkg.routines.get('f')!, 0, ['a'])!.params.length, 1);
});

async function blueprint() {
  return blueprintSchema.parse(JSON.parse(await readFile('resources/blueprints/crm.yaml', 'utf8')));
}

function generatedSnapshot(input: Snapshot, plan: CompositionPlan, nextBlueprint: Blueprint): Snapshot {
  const sources = { ...input.sources },
    sourceInventory = { ...input.sourceInventory },
    bases = { ...input.bases };
  for (const operation of plan.operations) {
    if (operation.path.startsWith(input.sourceDir + '/')) {
      const file = operation.path.slice(input.sourceDir.length + 1);
      if (operation.content === null) {
        delete sources[file];
        delete sourceInventory[file];
      } else {
        sources[file] = operation.content;
        sourceInventory[file] = operation.after!;
      }
    } else if (operation.reason === 'retain-generated-base') bases[operation.after!] = operation.content!;
  }
  return { ...input, blueprint: nextBlueprint, state: plan.state, sources, sourceInventory, bases };
}

test('unhosting a summary allocates a distinct stable page and replans without changes', async (t) => {
  const { ctx } = await fixture();
  t.after(() => rm(ctx.root, { recursive: true, force: true }));
  const original = await blueprint();
  await writeJson(ctx.root + '/app.blueprint.yaml', original);
  const input = await snapshot(ctx, 'app.blueprint.yaml', { validation: 'source-only' }),
    initial = planComposition(input);
  assert.equal(initial.status, 'materializable');
  assert.equal(initial.allocations.CustomerList!.page, initial.allocations.CustomerSummary!.page);
  const standalone = { ...original, connections: [] },
    afterInitial = generatedSnapshot(input, initial, standalone),
    unhost = planComposition(afterInitial);
  assert.equal(unhost.status, 'materializable', JSON.stringify(unhost.diagnostics));
  assert.equal(unhost.allocations.CustomerList!.page, initial.allocations.CustomerList!.page);
  assert.notEqual(unhost.allocations.CustomerSummary!.page, unhost.allocations.CustomerList!.page);
  assert.notEqual(unhost.allocations.CustomerSummary!.page, unhost.allocations.CustomerList!.dialog);
  const afterUnhost = generatedSnapshot(afterInitial, unhost, standalone),
    pages = Object.values(afterUnhost.sources).flatMap((source) =>
      declarations(source)
        .filter((node) => node.kind === 'page')
        .map((node) => node.key),
    );
  assert.equal(new Set(pages).size, pages.length);
  const repeat = planComposition(afterUnhost);
  assert.equal(repeat.status, 'materializable');
  assert.deepEqual(repeat.allocations, unhost.allocations);
  assert.deepEqual(repeat.operations, []);
});

